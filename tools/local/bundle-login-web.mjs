import { build, version } from '../../.local/tools/login-web/node_modules/esbuild/lib/main.js';
import { writeFileSync } from 'node:fs';

if (version !== '0.25.12') throw new Error('Use esbuild 0.25.12 for the checked-in bundle');
const result = await build({
    entryPoints: ['iOS/LoginResources/login.js'],
    bundle: true, format: 'esm', target: 'safari15', write: false,
    legalComments: 'inline',
    plugins: [{
        name: 'login-has-no-audio',
        setup(plugin) {
            // Login uses the Mac's console and lossless VNC. Do not bring the
            // unrelated high-performance audio WASM runtime into this app.
            plugin.onResolve({ filter: /\/audio-(decoder|sink)\.js$/ }, (args) => ({ path: args.path, namespace: 'login-audio' }));
            plugin.onLoad({ filter: /.*/, namespace: 'login-audio' }, (args) => ({
                contents: args.path.includes('decoder')
                    ? 'export class AacEldDecoder { static async create() { throw new Error("Audio is disabled in the login view"); } }'
                    : 'export class AudioSink { static isSupported() { return false; } static async create() { throw new Error("Audio is disabled in the login view"); } }',
                loader: 'js',
            }));
        },
    }],
});
// noVNC performs async browser capability checks. A single async script avoids
// file-origin ES-module imports in WKWebView while retaining those checks.
writeFileSync('iOS/LoginResources/login.bundle.js',
    '// Generated by tools/local/build-login-web.sh; source and licenses in ThirdParty/LoginVNC.\n' +
    '(async () => {\n' + result.outputFiles[0].text + '\n})().catch(() => {\n' +
    'window.webkit.messageHandlers.macLogin.postMessage({type:"failure", value:"无法初始化登录画面。"});\n});\n');
